"""PDF export of an itinerary (Module 4, step 4) using fpdf2."""
from collections import defaultdict
from datetime import timedelta

from fpdf import FPDF


def _t(s):
    """Core PDF fonts only support Latin-1 characters."""
    return str(s).encode("latin-1", "replace").decode("latin-1")


def itinerary_pdf(trip, it):
    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()

    pdf.set_fill_color(13, 148, 136)
    pdf.rect(0, 0, 210, 28, "F")
    pdf.set_text_color(255, 255, 255)
    pdf.set_font("Helvetica", "B", 18)
    pdf.set_xy(10, 8)
    pdf.cell(0, 8, _t(f"PackMY - {it.title}"))
    pdf.set_font("Helvetica", "", 10)
    pdf.set_xy(10, 17)
    end = trip.start_date + timedelta(days=trip.days - 1)
    pdf.cell(0, 6, _t(f"{trip.start_date:%d %b %Y} - {end:%d %b %Y}  |  {trip.travellers} traveller(s)  |  "
                      f"Budget RM{trip.budget:,.0f}  |  Estimated RM{it.total_cost:,.0f}"))
    pdf.set_text_color(30, 30, 30)
    pdf.set_y(34)

    if it.accommodation:
        pdf.set_font("Helvetica", "B", 11)
        pdf.cell(0, 6, _t(f"Stay: {it.accommodation.name}"), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 9)
    pdf.multi_cell(0, 5, _t(it.summary_text))
    pdf.ln(3)

    days = defaultdict(list)
    for s in it.segments:
        days[s.day_no].append(s)
    for d in range(1, trip.days + 1):
        pdf.set_font("Helvetica", "B", 12)
        pdf.set_fill_color(240, 253, 250)
        pdf.cell(0, 8, _t(f"Day {d} - {trip.start_date + timedelta(days=d - 1):%A, %d %b}"),
                 fill=True, new_x="LMARGIN", new_y="NEXT")
        if not days[d]:
            pdf.set_font("Helvetica", "I", 10)
            pdf.cell(0, 7, "Free day", new_x="LMARGIN", new_y="NEXT")
        for s in days[d]:
            pdf.set_font("Helvetica", "B", 10)
            pdf.cell(28, 6, _t(f"{s.arrive_time}-{s.depart_time}"))
            pdf.cell(110, 6, _t(s.asset.name))
            pdf.set_font("Helvetica", "", 9)
            pdf.cell(0, 6, _t(f"RM{s.cost:,.0f}  |  {s.travel_km:.1f} km"), new_x="LMARGIN", new_y="NEXT")
            pdf.set_x(38)
            pdf.set_text_color(100, 100, 100)
            pdf.multi_cell(0, 4.5, _t(s.asset.description or ""))
            pdf.set_text_color(30, 30, 30)
        pdf.ln(2)

    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(0, 8, "Expense breakdown", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 9)
    for e in sorted(it.expenses, key=lambda e: (e.day_no, e.category)):
        day = "Trip" if e.day_no == 0 else f"Day {e.day_no}"
        pdf.cell(18, 5, day)
        pdf.cell(30, 5, _t(e.category))
        pdf.cell(110, 5, _t(e.description))
        pdf.cell(0, 5, f"RM{e.amount:,.2f}", align="R", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "B", 10)
    pdf.cell(158, 7, "Total")
    pdf.cell(0, 7, f"RM{it.total_cost:,.2f}", align="R", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "I", 8)
    pdf.ln(4)
    pdf.multi_cell(0, 4, "Costs are estimates generated by PackMY. Please check opening hours and prices before you travel.")
    return bytes(pdf.output())
